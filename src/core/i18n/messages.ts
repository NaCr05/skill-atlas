export const messageCatalogs: Readonly<Record<Language, Readonly<Record<MessageKey, string>>>> = {
  zh: zhMessages,
  en: enMessages,
};

export function translateMessage(
  key: MessageKey,
  language: Language,
  values: MessageValues = {},
): string {
  return messageCatalogs[language][key].replace(/\{([a-zA-Z][\w-]*)\}/g, (token, name: string) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : token
  ));
}
